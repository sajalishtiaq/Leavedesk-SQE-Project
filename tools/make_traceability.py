#!/usr/bin/env python3
"""Builds docs/team/04-traceability.md and FAILS if any requirement has no automated test.
Pytest tests are matched by name fragments against `pytest --collect-only`; E2E tests by id in e2e/tests/*.spec.ts."""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAP = {  # requirement -> (business rules, pytest fragments, e2e ids)
    "FR-A1": ("-", ["test_apply_success_creates_pending_request", "test_apply_requires_authentication", "test_admin_can_apply_too", "test_generated_case[applyLeave"], ["UC1-MAIN", "UC1-A1"]),
    "FR-A2": ("BR5", ["test_working_days", "test_validate_no_working_days", "test_apply_weekend_only_rejected"], ["UC1-A2"]),
    "FR-A3": ("BR1", ["test_validate_balance_boundary_3_point", "test_apply_balance_boundary", "test_apply_rejection_leaves_shared_record_unchanged", "test_balance_message_exact"], ["UC1-E2"]),
    "FR-A4": ("BR5", ["test_validate_end_before_start", "test_validate_crosses_year", "test_validate_start_in_past", "test_apply_start_date_boundary", "test_apply_calendar_year_boundary", "test_apply_end_before_start"], []),
    "FR-A5": ("BR6", ["test_overlap_boundaries", "test_overlap_only_counts_pending_and_approved", "test_apply_overlap_boundaries", "test_apply_repeated_request_is_rejected_no_duplicate", "test_apply_overlap_depends_on_existing_status"], ["UC1-E3"]),
    "FR-A6": ("BR1", ["test_apply_leave_type_id_partitions", "test_apply_reason_length_boundaries", "test_apply_invalid_date_values", "test_apply_body_must_be_json_object", "test_generated_case[applyLeave"], ["UC1-E1"]),
    "FR-B1": ("BR2, BR3", ["test_pending_to_approved_updates_status_and_shared_balance", "test_approve_updates_balance_and_status", "test_repeated_approve_does_not_double_count"], ["UC2-MAIN", "UC2-A2"]),
    "FR-B2": ("BR3", ["test_pending_to_rejected_does_not_touch_balance", "test_reject_requires_note", "test_review_note_length_boundary"], ["UC2-A1", "UC2-E1"]),
    "FR-B3": ("BR2, BR3", ["test_review_decision_table", "test_disallowed_review_from_final_states", "test_admin_required_decorator_on_team_endpoint", "test_state_transition_matrix"], ["UC4-E2", "UC4-ADMIN"]),
    "FR-B4": ("BR3, BR4", ["test_cancel_decision_table", "test_cancel_start_date_boundary", "test_cancel_approved_restores_balance", "test_cancel_twice_is_rejected_no_double_refund", "test_state_transition_matrix"], ["UC3-MAIN", "UC3-A1", "UC3-A2", "UC3-E1", "UC3-E2"]),
    "FR-B5": ("BR1", ["test_approve_fails_when_balance_consumed_by_another_approval", "test_approve_balance_boundary", "test_approve_rejected_when_not_enough_balance", "test_approve_survives_database_outage"], ["UC2-E2"]),
    "FR-B6": ("-", ["test_owner_admin_can_view_but_other_employee_gets_404", "test_employee_sees_only_own_requests", "test_admin_sees_all_requests", "test_balances_user_id_permissions"], []),
}


def collect():
    out = subprocess.run([sys.executable, "-m", "pytest", "--collect-only", "-q", "-o", "addopts=", "-p", "no:cacheprovider"], cwd=ROOT, capture_output=True, text=True).stdout
    return [l for l in out.splitlines() if "::" in l]


def main():
    nodes = collect()
    e2e = "\n".join(p.read_text() for p in (ROOT / "e2e" / "tests").glob("*.spec.ts"))
    rows, missing = [], []
    for fr, (br, frags, ids) in MAP.items():
        n_py = sum(any(f in node for f in frags) for node in nodes)
        found_e2e = [i for i in ids if re.search(rf"'{i}[ '\-]", e2e)]
        if n_py == 0 or len(found_e2e) != len(ids):
            missing.append(fr)
        rows.append(f"| {fr} | {br} | {n_py} | {', '.join(found_e2e) or '-'} | {'COVERED' if fr not in missing else 'GAP'} |")
    md = ["# 04. Traceability Matrix (generated by `tools/make_traceability.py`)", "",
          "| Requirement | Business rules | Automated pytest cases (unit + API + generated) | E2E use-case flows | Status |", "|---|---|---|---|---|", *rows, "",
          f"Requirements coverage = {len(MAP) - len(missing)}/{len(MAP)} = {100 * (len(MAP) - len(missing)) / len(MAP):.0f} %", ""]
    (ROOT / "docs/team/04-traceability.md").write_text("\n".join(md))
    print("\n".join(md))
    if missing:
        sys.exit(f"requirements without tests: {missing}")


if __name__ == "__main__":
    main()
